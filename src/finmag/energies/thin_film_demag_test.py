def test_thin_film_demag_added_to_simulation_directly():
    box = mesh.create_box(
        MPI.COMM_WORLD, [(0.0, 0.0, 0.0), (5.0, 5.0, 5.0)], [2, 2, 2],
        mesh.CellType.tetrahedron)
    sim = Simulation(box, Ms_CONST, unit_length=1e-9, name="thin_film_demag_direct")
    sim.set_m((0.0, 0.0, 1.0))
    sim.add(ThinFilmDemag())
    assert sim.has_interaction("ThinFilmDemag")
    assert sim.total_energy() == pytest.approx(0.0, abs=1e-25)
    interaction = sim.get_interaction("ThinFilmDemag")
    H = interaction.compute_field().reshape((3, -1)).T
    expected = np.zeros_like(H)
    expected[:, 2] = -Ms_CONST
    np.testing.assert_allclose(H, expected, rtol=1e-12)
