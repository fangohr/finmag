def test_explicit_field_strength_bypasses_ms_average():
    domain = _cube()
    m, Ms = _fields(domain, (1.0, 0.0, 0.0), Ms=1.0e6)
    demag = ThinFilmDemag(direction="x", field_strength=250.0)
    demag.setup(m, Ms, unit_length=1e-9)
    H = demag.compute_field().reshape((3, -1)).T
    expected = np.zeros_like(H)
    expected[:, 0] = -250.0 * 1.0
    np.testing.assert_allclose(H, expected, rtol=1e-14)


def test_default_field_strength_is_ms_box_average():
    """``field_strength=None`` (the default) recovers a uniform ``Ms``
    exactly via the box average, matching ``test_thin_film_demag`` above but
    asserting the intermediate ``strength`` explicitly."""
    domain = _cube()
    m, Ms = _fields(domain, (0.0, 0.0, 1.0), Ms=Ms_CONST)
    demag = ThinFilmDemag()
    demag.setup(m, Ms, unit_length=1e-9)
    np.testing.assert_allclose(demag.strength, Ms_CONST, rtol=1e-10)


def test_compute_energy_is_the_legacy_literal_zero():
    domain = _cube()
    m, Ms = _fields(domain, (0.0, 0.0, 1.0))
    demag = ThinFilmDemag()
    demag.setup(m, Ms, unit_length=1e-9)
    assert demag.compute_field() is not None  # sanity: setup succeeded
    assert demag.compute_energy() == 0


