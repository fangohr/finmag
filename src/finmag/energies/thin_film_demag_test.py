def test_compute_field_is_recomputed_fresh_every_call():
    """Not a legacy-file transcription, but a direct pin of the "not cached"
    contract legacy's own ``compute_field`` relies on (it always reads
    ``self.m.get_numpy_array_debug()`` fresh) -- worth pinning explicitly
    given the documented ``DiscreteTimeZeeman`` legacy caching defect
    elsewhere in this port (see ``zeeman.py``)."""
    domain = _cube()
    m, Ms = _fields(domain, (1.0, 0.0, 0.0))
    demag = ThinFilmDemag()
    demag.setup(m, Ms, unit_length=1e-9)

    first = demag.compute_field()
    np.testing.assert_allclose(first, np.zeros_like(first), atol=1e-14)

    m.set((0.0, 0.0, 1.0))
    second = demag.compute_field()
    # compute_field() is component-blocked (Task 31); compare against the
    # blocked m (here H == -Ms * m because m lies purely along the z direction).
    expected = -Ms_CONST * m.get_ordered_numpy_array_xxx()
    np.testing.assert_allclose(second, expected, rtol=1e-14)


