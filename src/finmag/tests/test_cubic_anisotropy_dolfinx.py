def test_non_orthogonal_non_unit_axes_are_silently_accepted():
    """Legacy ``CubicAnisotropy`` performs no normalisation and no
    orthogonality check on ``u1``/``u2`` -- it documents them as "should be
    unit vectors" but does not enforce it (see
    ``dev/dolfinx/prototype.py::cubic_anisotropy_energy``'s investigation
    note, and the legacy module's own ``cubic_anisotropy_test.py``, whose
    axes ``u1=(0,-0.7071,0.7071)``/``u2=(0,0.7071,0.7071)`` are not exactly
    unit vectors: ``0.7071**2 * 2 == 0.99980082 != 1``). This port preserves
    that behaviour exactly rather than raising or silently renormalising."""
    u1 = np.array((1.0, 0.3, 0.0))  # not unit length
    u2 = np.array((0.2, 1.0, 0.1))  # not orthogonal to u1, not unit length
    assert not np.isclose(np.linalg.norm(u1), 1.0)
    assert not np.isclose(np.dot(u1, u2), 0.0)

    domain = _cube()
    m, Ms = _fields(domain, (0.3, 0.4, np.sqrt(1 - 0.3**2 - 0.4**2)))
    ca = CubicAnisotropy(u1, u2, K1=1.0e4, K2=5.0e3, K3=1.0e2, assemble=True)
    ca.setup(m, Ms, unit_length=1.0)

    np.testing.assert_allclose(ca.u1_value, u1)
    np.testing.assert_allclose(ca.u2_value, u2)
    np.testing.assert_allclose(ca.u3_value, np.cross(u1, u2))
    assert np.isfinite(ca.compute_energy())


