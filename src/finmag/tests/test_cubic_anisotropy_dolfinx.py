def test_native_oracle_k2_typo_is_dormant_for_constant_k2():
    """K2-only native-field evidence for the ``native/src/llg/energy.cc:116``
    typo (``hz[i] += K2[2]*(...)`` -- fixed node index ``2`` where every other
    line uses per-node ``K2[i]``).

    Because ``K2`` is spatially constant here the nodal ``K2`` array is
    uniform, so ``K2[2] == K2[i]`` and the typo is numerically dormant: the
    legacy native field equals the *correct* hand-derived analytic field to
    floating-point noise. This test pins that known fact as executable
    evidence -- the correct derivation (computed independently from the
    fixture's own ``m_vertex``) reproduces the legacy native ``H_vertex``,
    including the ``hz`` component the typo touches."""
    case = NATIVE_ORACLE["cases"]["k2_only"]
    physical = case["physical_parameters"]
    K1 = physical["K1"]["value"]
    K2 = physical["K2"]["value"]
    K3 = physical["K3"]["value"]
    assert (K1, K3) == (0, 0) and K2 != 0  # genuinely K2-isolated

    m_q = case["quantities"][0]
    assert m_q["name"] == "m_vertex"
    m_vertex = np.asarray(m_q["values"])
    ref_H = np.asarray(case["quantities"][1]["values"])

    H_correct = _analytic_field(
        m_vertex, physical["u1"]["value"], physical["u2"]["value"],
        K1, K2, K3, physical["Ms"]["value"])

    scale = np.abs(ref_H).max()
    # Whole field (incl. the hz component the typo indexes) matches the
    # correct derivation -> typo demonstrably dormant for constant K2.
    np.testing.assert_allclose(H_correct, ref_H, rtol=1e-11, atol=1e-11 * scale)

    # And the port (correct field) reproduces the native oracle too.
    H_port, _ = _native_case_port_field(case)
    np.testing.assert_allclose(H_port, ref_H, rtol=1e-11, atol=1e-11 * scale)


@pytest.mark.parametrize("case_name", ["k2_only", "all_nonzero"])
def test_box_field_converges_to_analytic_field_under_refinement(case_name):
    """Independent arbiter for the analytic (assemble=False) field: the
    box-assemble (assemble=True) weak-form-derivative field is a distinct
    discretisation that must converge toward the *analytic* nodal field (this
    port's assemble=False output), not toward the buggy K2[2] variant, as the
    mesh is refined. Asserts monotone decrease of the relative L2 gap across
    three refinement levels."""
    case = NATIVE_ORACLE["cases"][case_name]
    physical = case["physical_parameters"]
    u1, u2 = physical["u1"]["value"], physical["u2"]["value"]
    K1 = physical["K1"]["value"]
    K2 = physical["K2"]["value"]
    K3 = physical["K3"]["value"]
    Ms_value = physical["Ms"]["value"]

    gaps = []
    for n in (2, 4, 8):
        domain = mesh.create_box(
            MPI.COMM_WORLD, [(0.0, 0.0, 0.0), (0.7, 0.7, 0.7)],
            [n, n, n], mesh.CellType.tetrahedron)
        S3 = fem.functionspace(domain, ("Lagrange", 1, (3,)))
        DG = fem.functionspace(domain, ("DG", 0))
        m = Field(S3, _oracle_m(), name="m")
        Ms = Field(DG, Ms_value, name="Ms")

        analytic = CubicAnisotropy(u1, u2, K1, K2, K3)
        analytic.setup(m, Ms, unit_length=1e-9)
        H_analytic = analytic.compute_field()

        box = CubicAnisotropy(u1, u2, K1, K2, K3, assemble=True)
        box.setup(m, Ms, unit_length=1e-9)
        H_box = box.compute_field()

        gaps.append(
            np.linalg.norm(H_box - H_analytic) / np.linalg.norm(H_analytic))

    assert gaps[0] > gaps[1] > gaps[2], gaps
    assert gaps[-1] < gaps[0]  # net convergence


