"""Direct DOLFINx cubic-anisotropy port (Task 14).

Validates the ported ``finmag.energies.cubic_anisotropy.CubicAnisotropy``
against:

- the legacy module's own analytic reference values (transcribed from
  ``finmag.energies.cubic_anisotropy_test.py::test_cubic_anisotropy_energy``:
  same ``K1``/``K2``/``K3``/``u1``/``u2`` constants, same uniform
  ``m = (0, 0, 1)``);
- cubic-symmetry easy/hard-axis energy ordering for the standard orthonormal
  crystallographic axes (``K1 > 0``): ``E([100]) == 0``,
  ``E([110]) - E([100]) == K1/4 * V``, ``E([111]) - E([100]) == K1/3 * V``
  (derived from the transcribed energy-density form itself, not assumed);
- the ``K2``/``K3`` contributions in isolation (the other two constants set
  to zero);
- axis-handling behavior transcribed exactly from the legacy class: ``u3 =
  u1 x u2``, and ``u1``/``u2`` are used *as given* -- neither renormalised
  nor checked for orthogonality (matching
  ``dev/dolfinx/prototype.py::cubic_anisotropy_energy``'s documented
  investigation and the legacy class's own non-unit,
  not-quite-orthogonal ``cubic_anisotropy_test.py`` axes);
- by-name deferral of spatially varying ``K1``/``K2``/``K3``/``u1``/``u2``
  and of ``compute_field()`` under the legacy-default ``assemble=False``
  (the unported native/direct field path);
- a coordinate-ordered legacy oracle fixture comparison (field + energy)
  against ``src/finmag/tests/fixtures/cubic_anisotropy_oracle.json``,
  regenerated by
  ``src/finmag/tests/fixtures/gen_cubic_anisotropy_oracle.py``;
- ``Simulation``/``sim.add(...)`` integration, including a dynamics effect.

[Claude Sonnet 5]
"""

import json
import os

