def test_cubic_anisotropy_affects_dynamics():
    """A cubic-anisotropy-only simulation, started away from an easy axis,
    must precess/relax under a genuinely nonzero effective field -- i.e. the
    interaction is actually wired into the LLG dynamics, not just present in
    the energy bookkeeping."""
