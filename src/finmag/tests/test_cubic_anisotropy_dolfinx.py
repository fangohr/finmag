def test_cubic_anisotropy_affects_dynamics():
    """A cubic-anisotropy-only simulation, started away from an easy axis,
    must precess/relax under a genuinely nonzero effective field -- i.e. the
    interaction is actually wired into the LLG dynamics, not just present in
    the energy bookkeeping."""
    box = mesh.create_box(
        MPI.COMM_WORLD, [(0.0, 0.0, 0.0), (5.0, 5.0, 5.0)], [2, 2, 2],
        mesh.CellType.tetrahedron)
    sim = Simulation(box, 8.6e5, unit_length=1e-9, name="cubic_anis_dynamics")
    # A generic, low-symmetry direction (not aligned with any easy/hard axis
    # of the standard cubic axes below), so the effective field is not
    # parallel to m and the LLG torque m x H_eff is genuinely nonzero.
    m0 = np.array((1.0, 0.3, 0.1))
    m0 /= np.linalg.norm(m0)
    sim.set_m(tuple(m0))
    sim.alpha = 0.5
    sim.add(CubicAnisotropy(
        (1, 0, 0), (0, 1, 0), 1.0e4, assemble=True))

    field0 = sim.effective_field()
    assert np.max(np.abs(field0)) > 0.0

    sim.run_until(1e-9)
    m_after = sim.m.reshape((3, -1)).T[0]
    assert not np.allclose(m_after, m0, atol=1e-6)
