import pytest
from dolfinx import fem, mesh
from mpi4py import MPI

from finmag.energies import CubicAnisotropy
from finmag.field import Field
from finmag.sim.sim import Simulation

_FIXTURE = os.path.join(
    os.path.dirname(__file__), "fixtures", "cubic_anisotropy_oracle.json")
ORACLE = json.load(open(_FIXTURE))
CASE = ORACLE["cases"]["cubic_3d"]

# Same constants/axes as finmag.energies.cubic_anisotropy_test.py.
UNIT_LENGTH = 1e-9
Ms_LEGACY = 876626
K1_LEGACY = -8608726
K2_LEGACY = -13744132
K3_LEGACY = 1100269
U1_LEGACY = (0, -0.7071, 0.7071)
U2_LEGACY = (0, 0.7071, 0.7071)


def _cube(cells=2):
    return mesh.create_unit_cube(MPI.COMM_WORLD, cells, cells, cells)


def _fields(domain, m_value, Ms=8.0e5):
    S3 = fem.functionspace(domain, ("Lagrange", 1, (3,)))
    DG = fem.functionspace(domain, ("DG", 0))
    return Field(S3, m_value, name="m"), Field(DG, Ms, name="Ms")


def _domain_volume(domain):
    import ufl

    local = fem.assemble_scalar(fem.form(fem.Constant(domain, 1.0) * ufl.dx))
    return domain.comm.allreduce(local, op=MPI.SUM)


