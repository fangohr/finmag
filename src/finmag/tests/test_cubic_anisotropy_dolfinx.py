# assemble=False (default): ported native analytic field
# --------------------------------------------------------------------------

MU0 = 4.0 * np.pi * 1e-7


def _analytic_field(m_vecs, u1, u2, K1, K2, K3, Ms):
    """Reference per-node cubic-anisotropy field ``H = -1/(mu0 Ms) dE/dm``.

    Hand-derived (chain rule through ``a=u1.m``, ``b=u2.m``, ``c=u3.m``) from
    the legacy energy density ``K1*(a^2 b^2 + b^2 c^2 + c^2 a^2) +
    K2*a^2 b^2 c^2 + K3*(a^4 b^4 + b^4 c^4 + c^4 a^4)``; this is the analytic
    field the legacy native routine ``compute_cubic_field`` implements for
    ``assemble=False``. Independent of the DOLFINx port under test.
    """
    u1 = np.asarray(u1, dtype=float)
    u2 = np.asarray(u2, dtype=float)
    u3 = np.cross(u1, u2)
    m_vecs = np.asarray(m_vecs, dtype=float).reshape(-1, 3)
    a = m_vecs @ u1
    b = m_vecs @ u2
    c = m_vecs @ u3
    g1 = 2 * K1 * a * (b**2 + c**2) + 2 * K2 * a * b**2 * c**2 \
        + 4 * K3 * a**3 * (b**4 + c**4)
    g2 = 2 * K1 * b * (a**2 + c**2) + 2 * K2 * b * a**2 * c**2 \
        + 4 * K3 * b**3 * (a**4 + c**4)
    g3 = 2 * K1 * c * (a**2 + b**2) + 2 * K2 * c * a**2 * b**2 \
        + 4 * K3 * c**3 * (a**4 + b**4)
    dEdm = g1[:, None] * u1 + g2[:, None] * u2 + g3[:, None] * u3
    return -(1.0 / (MU0 * Ms)) * dEdm


