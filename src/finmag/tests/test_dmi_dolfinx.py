def test_interfacial_dmi_affine_ramp_matches_legacy_form_exactly():
    """Transcribed from ``finmag.energies.dmi.DMI_interfacial``: for
    ``mx = a``, ``my = b`` constant and ``mz = c*x + e*y``, the bracket
    reduces exactly to ``a*c + b*e`` (every ``mz``-multiplied derivative
    vanishes since ``mx``/``my`` are constant)."""
    domain = mesh.create_unit_cube(MPI.COMM_WORLD, 3, 3, 3)
    a, b, c, e = 0.2, 0.3, 0.5, 0.8
    D = 5.0e-3

    def m_expr(sign):
        def f(x):
            return np.vstack(
                (np.full(x.shape[1], a), np.full(x.shape[1], b),
                 sign * (c * x[0] + e * x[1]))
            )

        return f

    m_pos, Ms = _fields(domain, m_expr(1.0))
    m_neg, _ = _fields(domain, m_expr(-1.0))

    pos = DMI(D, dmi_type="interfacial")
    pos.setup(m_pos, Ms, unit_length=1.0)
    neg = DMI(D, dmi_type="interfacial")
    neg.setup(m_neg, Ms, unit_length=1.0)

    expected = D * (a * c + b * e)
    assert pos.compute_energy() == pytest.approx(expected, rel=1e-12)
    assert neg.compute_energy() == pytest.approx(-expected, rel=1e-12)


