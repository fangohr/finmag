from finmag.sim.sim import Simulation, sim_with

_FIXTURE = os.path.join(os.path.dirname(__file__), "fixtures", "dmi_oracle.json")
ORACLE = json.load(open(_FIXTURE))
CASES = ORACLE["cases"]


def _cube(cells=2, dim=3):
    if dim == 1:
        return mesh.create_interval(MPI.COMM_WORLD, cells, [0.0, 2.0])
    if dim == 2:
        return mesh.create_unit_square(MPI.COMM_WORLD, cells, cells)
    return mesh.create_unit_cube(MPI.COMM_WORLD, cells, cells, cells)


def _fields(domain, m_callable_or_value, Ms=8.0e5):
    S3 = fem.functionspace(domain, ("Lagrange", 1, (3,)))
    DG = fem.functionspace(domain, ("DG", 0))
    return Field(S3, m_callable_or_value, name="m"), Field(DG, Ms, name="Ms")


