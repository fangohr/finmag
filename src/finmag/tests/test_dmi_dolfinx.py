@pytest.mark.parametrize("dmi_type", ("auto", "1d", "2d", "3d", "interfacial"))
def test_uniform_m_gives_zero_dmi_energy(dmi_type):
    """Uniform ``m`` has zero gradient everywhere, so both the bulk
    (``m . curl(m)``) and interfacial energy *densities* vanish identically
    and the total energy is exactly zero.

    The box-assembled *field* is a different story: ``compute_field()`` is
    the weak-form derivative ``d/dm [D m.curl(m)] = D(v.curl(m) + m.curl(v))``
    for test function ``v``; even when ``curl(m) == 0`` the second term
    ``D m.curl(v)`` need not vanish, since it depends on the *test* function's
    curl, not ``m``'s. This is not a discretisation artefact of the port: it
    is the same well-known physical boundary/edge-canting contribution DMI
    produces at a free surface even for otherwise-uniform magnetisation, and
    follows from the identical UFL derivative the legacy class also uses. It
    is exercised only for energy here; see the chirality/oracle tests below
    for field-level checks."""
    dim = {"1d": 1}.get(dmi_type, 3)
    domain = _cube(dim=dim if dim in (1, 2, 3) else 3)
    m, Ms = _fields(domain, (0.6, 0.8, 0.0))
    dmi = DMI(5e-3, dmi_type=dmi_type)
    dmi.setup(m, Ms, unit_length=1.0e-9)
    assert dmi.compute_energy() == pytest.approx(0.0, abs=1e-25)


