def test_bulk_dmi_affine_twist_field_matches_transcribed_times_curl_exactly():
    """Transcribed from ``finmag.tests.test_dmi_terms.
    test_dmi_term3d_matches_analytical_solution``: for
    ``m = (-y/2, x/2, c)``, ``curl(m) = (0, 0, 1)`` so ``m . curl(m) = c``
    everywhere, exactly (the field is affine, so CG1 captures it exactly)."""
    domain = mesh.create_unit_cube(MPI.COMM_WORLD, 4, 4, 4)
    c = 1.0

    def m_expr(x):
        return np.vstack((-0.5 * x[1], 0.5 * x[0], np.full(x.shape[1], c)))

    m, Ms = _fields(domain, m_expr)
    dmi = DMI(1.0, dmi_type="auto")
    dmi.setup(m, Ms, unit_length=1.0)
    # Volume of the unit cube is 1, so E = D * c * V = c.
    assert dmi.compute_energy() == pytest.approx(c, rel=1e-13)


def test_bulk_dmi_chirality_sign_flips_with_handedness():
    domain = mesh.create_unit_cube(MPI.COMM_WORLD, 4, 4, 4)
    D = 5.0e-3
    c = 2.0

    def twist(sign):
        def f(x):
            return np.vstack(
                (-sign * 0.5 * x[1], sign * 0.5 * x[0], np.full(x.shape[1], c))
            )

        return f

    m_right, Ms = _fields(domain, twist(1.0))
    m_left, _ = _fields(domain, twist(-1.0))

    right = DMI(D, dmi_type="auto")
    right.setup(m_right, Ms, unit_length=1.0)
    left = DMI(D, dmi_type="auto")
    left.setup(m_left, Ms, unit_length=1.0)

    assert right.compute_energy() == pytest.approx(D * c, rel=1e-13)
    assert left.compute_energy() == pytest.approx(-D * c, rel=1e-13)
    assert right.compute_energy() == pytest.approx(-left.compute_energy(), rel=1e-13)


def test_bulk_dmi_helix_chirality_is_an_exact_sign_identity():
    """A genuine sinusoidal helix ``m = (0, cos(kx), sin(kx))``: negating
    ``k`` keeps the ``y``-component's nodal values identical (``cos`` is
    even) and exactly negates the ``z``-component's nodal values (``sin`` is
    odd). Algebraically, for a field depending only on ``x`` with a zero
    ``x``-component, that nodal transform exactly negates ``m . curl(m)`` --
    an identity of the two FEM functions themselves, not merely of the
    continuum limit, so it holds to machine precision regardless of the
    (mesh-dependent) discretisation error each side carries individually."""
    domain = mesh.create_unit_cube(MPI.COMM_WORLD, 3, 3, 3)
    k = 3.0

    def helix(sign):
        def f(x):
            return np.vstack(
                (np.zeros(x.shape[1]), np.cos(sign * k * x[0]),
                 np.sin(sign * k * x[0]))
            )

        return f

    m_pos, Ms = _fields(domain, helix(1.0))
    m_neg, _ = _fields(domain, helix(-1.0))

    pos = DMI(5.0e-3, dmi_type="auto")
    pos.setup(m_pos, Ms, unit_length=1.0)
    neg = DMI(5.0e-3, dmi_type="auto")
    neg.setup(m_neg, Ms, unit_length=1.0)

    E_pos = pos.compute_energy()
    E_neg = neg.compute_energy()
    assert E_pos != pytest.approx(0.0)
    assert E_pos + E_neg == pytest.approx(0.0, abs=1e-18)
    assert E_pos == pytest.approx(-E_neg, rel=1e-12)


