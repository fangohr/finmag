@pytest.mark.parametrize("unit_length", (1.0, 2.0, 5.0))
def test_1d_dmi_energy_is_independent_of_unit_length(unit_length):
    """``dim - 1 == 0`` for a 1D mesh, so the legacy
    ``unit_length ** (dim - 1)`` convention predicts no unit_length
    dependence at all -- an exact, easily overlooked edge case."""
    domain = mesh.create_interval(MPI.COMM_WORLD, 4, [0.0, 2.0])
    b, c = 0.3, 0.7

    def m_expr(x):
        return np.vstack(
            (np.zeros(x.shape[1]), np.full(x.shape[1], b), c * x[0])
        )

    m, Ms = _fields(domain, m_expr)
    dmi = DMI(5.0e-3, dmi_type="1d")
    dmi.setup(m, Ms, unit_length=unit_length)
    expected = 5.0e-3 * (-b * c) * 2.0  # mesh length 2.0, unit_length**0 == 1
    assert dmi.compute_energy() == pytest.approx(expected, rel=1e-12)


@pytest.mark.parametrize("unit_length", (1.0, 3.0))
def test_2d_dmi_energy_scales_linearly_with_unit_length(unit_length):
    domain = mesh.create_unit_square(MPI.COMM_WORLD, 3, 3)
    p, q, c, d = 0.4, 0.5, 0.6, 0.9

    def m_expr(x):
        return np.vstack(
            (np.full(x.shape[1], p), np.full(x.shape[1], q), c * x[0] + d * x[1])
        )

    m, Ms = _fields(domain, m_expr)
    dmi = DMI(5.0e-3, dmi_type="2d")
    dmi.setup(m, Ms, unit_length=unit_length)
    expected = 5.0e-3 * (p * d - q * c) * unit_length  # Area 1, dim - 1 == 1
    assert dmi.compute_energy() == pytest.approx(expected, rel=1e-12)


