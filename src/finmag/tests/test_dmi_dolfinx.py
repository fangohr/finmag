def test_sim_with_dmi_builds_and_computes():
    box = mesh.create_box(
        MPI.COMM_WORLD, [(0.0, 0.0, 0.0), (5.0, 5.0, 5.0)], [2, 2, 2],
        mesh.CellType.tetrahedron)
    sim = sim_with(
        box, Ms=8.6e5, m_init=(1.0, 0.0, 0.0), unit_length=1e-9,
        D=5e-3, demag_solver=None)
    assert sim.has_interaction("DMI")
    dmi = sim.get_interaction("DMI")
    assert dmi.name == "DMI"
    assert np.isfinite(dmi.compute_energy())
    assert np.all(np.isfinite(dmi.compute_field()))


def test_dmi_added_to_simulation_directly():
    box = mesh.create_box(
        MPI.COMM_WORLD, [(0.0, 0.0, 0.0), (5.0, 5.0, 5.0)], [2, 2, 2],
        mesh.CellType.tetrahedron)
    sim = Simulation(box, 8.6e5, unit_length=1e-9, name="dmi_direct")
    sim.set_m((0.0, 0.0, 1.0))
    sim.add(DMI(5e-3))
    assert sim.has_interaction("DMI")
    assert np.isfinite(sim.total_energy())
