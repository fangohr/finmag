def test_finmagrc_solver_type_option_raises_by_name(tmp_path, monkeypatch):
    """Finding 4 (Task 11b review round 1): legacy ``FKDemag`` read
    ``demag/solver_type`` from ``.finmagrc`` when the kwarg was not given; the
    port had silently dropped that read, so a user config requesting e.g.
    'LU' would silently get Krylov instead. ``finmag.util.configuration`` has
    no env-var override, only a hardcoded homedir path list
    (``CONFIGURATION_FILES``), so that list is monkeypatched to a temp file --
    the module's own test-safe seam -- to exercise the real configparser
    code path without touching the developer's actual ``~/.finmagrc``."""
    from finmag.util import configuration as config_module

    finmagrc = tmp_path / "finmagrc"
    finmagrc.write_text("[demag]\nsolver_type = LU\n")
    monkeypatch.setattr(config_module, "CONFIGURATION_FILES", [str(finmagrc)])

    with pytest.raises(NotImplementedError, match="LU"):
        FKDemag()

    # An explicit kwarg still overrides the config file.
    FKDemag(solver_type="Krylov")

    # No [demag] section (or none at all) falls back to the Krylov default.
    finmagrc.write_text("[other]\nkey = value\n")
    FKDemag()


