def test_sorted_index_winding_produces_wrong_bem_with_unchanged_row_sums():
    """Pins the critical 11b discovery: naive ascending-index ("sorted")
    facet winding -- the winding DOLFINx's raw facet-vertex connectivity
    returns, before ``boundary_bem_arrays`` applies its outward-orientation
    flip -- produces a BEM matrix whose row sums are STILL approx -1 (the
    closed-surface solid-angle identity survives the corrupted winding), yet
    individual entries are wrong by far more than any legitimate
    discretisation/solver tolerance (~0.18 max-abs here). This demonstrates
    that ``test_bem_row_sum_identity_through_extraction`` alone cannot catch
    a winding/orientation bug -- only the golden-matrix pin can."""
    mesh = _kuhn_cube()
    S1 = fem.functionspace(mesh, ("Lagrange", 1))
    coords, oriented_cells, b2g = boundary_bem_arrays(mesh, S1)
    b2g = np.asarray(b2g, dtype=np.int64)

    # Deliberately corrupt the winding: sort each triangle's BEM-local vertex
    # indices ascending instead of using the outward-oriented winding.
    sorted_cells = np.sort(oriented_cells, axis=1)
    assert np.any(np.any(sorted_cells != oriented_cells, axis=1)), (
        "test setup: sorting must actually change at least one triangle's "
        "winding, or this test would not exercise the discovery"
    )

    bem_sorted, _ = compute_bem_fk_from_arrays(coords, sorted_cells, b2g)
    bem_oriented, _ = compute_bem_fk_from_arrays(coords, oriented_cells, b2g)

    np.testing.assert_allclose(bem_sorted.sum(axis=1), -np.ones(len(coords)),
                               rtol=0, atol=1e-10)
    assert np.abs(bem_sorted - bem_oriented).max() > 0.1


