    perm = _coord_permutation(coords, CUBE_COORDS)
    permuted = bem[np.ix_(perm, perm)]
    np.testing.assert_allclose(permuted, GOLDEN_BEM_FK, rtol=0,
                               atol=TOL_BEM_GOLDEN)


