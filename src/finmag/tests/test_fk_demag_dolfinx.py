def _scalar_quantity(case, name):
    for q in case["scalar_quantities"]:
        if q["name"] == name:
            return q
    raise KeyError(name)


def _quantity(case, name):
    for q in case["quantities"]:
        if q["name"] == name:
            return q
    raise KeyError(name)


def _oracle_compare(case_name, mesh, m_vec, Ms, unit_length, parameters=None):
    """Compare the port against a fixture case, with every tolerance read
    from the fixture itself (Finding 2) rather than hardcoded in the test."""
    case = CASES[case_name]
    demag, S3 = _demag_on(mesh, m_vec, Ms, unit_length, parameters=parameters)
    E = demag.compute_energy()
    avg = demag.average_field()
    # Task 31: component-blocked field -> owned-vertex per-node rows, sorted
    # against the matching owned-vertex coordinates.
    H = demag.compute_field().reshape((3, -1)).T
    n_owned = mesh.geometry.index_map().size_local
    coords = mesh.geometry.x[:n_owned, : mesh.geometry.dim]
    order = np.lexsort((coords[:, 2], coords[:, 1], coords[:, 0]))
    coords_s, H_s = coords[order], H[order]

    ref_coords = np.asarray(case["coordinates"]["values"])
    energy_q = _scalar_quantity(case, "energy")
    avg_q = _scalar_quantity(case, "average_field")
    H_q = _quantity(case, "H_vertex")
    ref_E = energy_q["value"]
    ref_avg = np.asarray(avg_q["value"])
    ref_H = np.asarray(H_q["values"])

    # meshes coincide vertex-for-vertex (create_box == legacy BoxMesh)
    assert coords_s.shape == ref_coords.shape
    np.testing.assert_allclose(coords_s, ref_coords, rtol=0, atol=1e-9)

    e_tol = energy_q["tolerances"]
    np.testing.assert_allclose(E, ref_E, atol=e_tol["absolute"],
                               rtol=e_tol["relative"])
    avg_tol = avg_q["tolerances"]
    np.testing.assert_allclose(avg, ref_avg, atol=avg_tol["absolute"],
                               rtol=avg_tol["relative"])
    H_tol = H_q["tolerances"]
    np.testing.assert_allclose(H_s, ref_H, atol=H_tol["absolute"],
                               rtol=H_tol["relative"])


